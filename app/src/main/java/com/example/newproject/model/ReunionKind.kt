package com.example.newproject.model

/**
 * 再会カードの枠に出ている1件が**どの種別か**。
 *
 * **文言だけで見分けない。** 同じ枠へ別種のものが出るので、種別が生成文の中にしか無いと
 * 表示側が条件分岐できず、検査も書けない（→ features/reunion_card.md 判断2）。
 *
 * **枠は排他1つ。** 併存させると `ReadingTrace` の拡張に加えて Nano 生成が
 * ノートあたり2回になり、Mutex 直列なので待ち時間が倍になる（同 判断1）。
 */
enum class ReunionKind {
    /** 本文にあった疑問文のうち、AIが未解決と選んだもの。 */
    Question,

    /** 西暦・版番号・金額を含む記述のうち、AIが古びうると選んだもの。 */
    Staleness,

    /**
     * 訪問履歴の俯瞰要約。**上2つが成立しないときの既定**であり、
     * 候補があったのにAIが「どれも該当しない」と返した回（空振り）もここへ記録する。
     */
    Overview
}

/**
 * 候補のどれも当てはまらないとAIが判断したときの表明語。
 *
 * **空振りは失敗ではない。** 候補は規則で列挙しているので、形は合っていても
 * 中身が該当しないことは普通に起きる。無理に1件選ばせると、
 * **前置きと中身が食い違ったカード**が出る（→ features/reunion_card.md「空振りの扱い」）。
 */
const val REUNION_NONE_TOKEN = "NONE"

/**
 * 応答が「どれも該当しない」の表明かどうか。
 *
 * **前後の飾りは許す。** 箇条書き記号や引用符を付けて返すモデルは実在するので、
 * 表明語だけを厳密一致で求めると、**空振りが「約束違反」に化けて記録されなくなる**。
 * 逆に部分一致にしないのは、本文中の候補文に `NONE` が含まれる場合と区別できなくなるため。
 */
fun isReunionNone(response: String): Boolean =
    response.trim().trim('-', '*', '•', '`', '"', '\'', ' ', '.', '。')
        .equals(REUNION_NONE_TOKEN, ignoreCase = true)
