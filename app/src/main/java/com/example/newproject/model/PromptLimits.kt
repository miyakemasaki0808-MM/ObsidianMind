package com.example.newproject.model

/**
 * **完成プロンプト全体**の入力上限と、そこへ載る可変部の取り分（UTF-16文字数）。
 *
 * [NoteExcerptLimits] が「本文をどれだけ載せるか」だけを決めるのに対し、こちらは
 * **指示文・タイトル・候補一覧・会話履歴を足した完成品**を閉じる。
 * 本文の抜粋に上限があっても、履歴・質問・候補名が伸びれば完成プロンプトは伸びるので、
 * 用途別上限だけでは入力を閉じたことにならない。
 *
 * ## 数字の出どころ
 *
 * **トークン計測から逆算した値ではない。** [MAX_PROMPT_CHARACTERS] は
 * **現行設計が意図する最大構成**（関連ノート＝指示文＋タイトル＋抜粋 800＋候補ブロック 3,500）に
 * 余白を足したもので、`PromptBudgetTest` がその構成の実寸を突き合わせている。
 *
 * こう決めたのは、**上限を「新しい制約」にしないため**。ここでどの経路の入力も
 * 短くならず、閉じるのは**意図しない伸び**（会話履歴の際限ない蓄積・異常に長い見出し）だけになる。
 * 部分予算を引き上げたら `PromptBudgetTest` が落ちるので、**この数字も一緒に決め直すことになる。**
 *
 * **トークン上限との関係は端末とモデル世代に依存する**ので、ここでは主張しない。
 * 実トークンでの余裕は androidTest の `PromptTokenBudgetTest` が測る。
 */
object PromptLimits {

    /**
     * 完成プロンプト全体の上限。**超えたぶんは本文側から削る**（→ `PromptBudget`）。
     *
     * 設計上ここまで伸びる経路は無い。**到達したら、下の部分予算のどれかが崩れている合図。**
     */
    const val MAX_PROMPT_CHARACTERS = 6_000

    /**
     * タイトル・見出し・出典ラベルの上限。
     *
     * ノート名はファイル名なので実質的に短いが、**セクション見出しはMarkdownの1行**であり
     * 長さの保証が無い。段落まるごとの見出しを持つノートで、見出しだけが抜粋を押し出さないようにする。
     */
    const val LABEL_CHARACTERS = 200

    /**
     * セクションチャットの会話履歴の取り分。**古い発言から落とす。**
     *
     * 履歴は往復のたびに伸びる一方で、上限が無かった。セクション本文の取り分
     * （[NoteExcerptLimits.SECTION] ＝1,500）より小さくしてあるのは、
     * **答える材料はセクション本文であって履歴ではない**ため。
     */
    const val SECTION_CHAT_HISTORY_CHARACTERS = 1_200

    /**
     * 質問1件の上限。
     *
     * 現在の質問はAIの候補をタップして送るので端末AIの出力枠（256トークン）に縛られるが、
     * **チャットへ自由入力を足したら縛りが消える**（ロードマップに候補として載っている）。先に閉じておく。
     */
    const val QUESTION_CHARACTERS = 400

    /**
     * ひとことへの返事のうち、**AIへ渡すぶん**の上限。**保存する返事は切らない。**
     *
     * 出力枠が256トークンしかないので、入力を長くしても返ってくる1文は変わらない。
     * 実際の切り出し（先頭と末尾を残して真ん中を落とす）は `excerptReplyForPrompt` が持つ。
     * **数字はここが正本**。`ai` と `domain` の両方から見えるのは葉の `model` だけなので、
     * ここに置かないと同じ意味の数字が2つに割れる。
     */
    const val REPLY_CHARACTERS = 400

    /** AIピッカーの自然文クエリの上限。**ユーザーが直接打つ唯一の入力**なので長さの保証が無い。 */
    const val QUERY_CHARACTERS = 200

    /**
     * AIピッカーの候補タイトル一覧の取り分。
     *
     * **タイトルは途中で切らない**（受け側がタイトルで照合するため、切ると黙って落ちる）。
     * 予算を超えるぶんは行ごと落とす。
     */
    const val PICKER_CANDIDATES_CHARACTERS = 2_000
}
